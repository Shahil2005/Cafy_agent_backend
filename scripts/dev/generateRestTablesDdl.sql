select string_agg(
  format('create table if not exists public.%I (%s%s);',
    c.relname,
    (select string_agg(
        format('%I %s%s%s',
          a.attname,
          format_type(a.atttypid, a.atttypmod),
          case
            when a.attidentity = 'a' then ' generated always as identity'
            when a.attidentity = 'd' then ' generated by default as identity'
            when a.attgenerated <> '' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
            when d.adbin is not null and pg_get_expr(d.adbin, d.adrelid) like 'nextval(%' then ' generated by default as identity'
            when d.adbin is not null then ' default ' || pg_get_expr(d.adbin, d.adrelid)
            else ''
          end,
          case when a.attnotnull then ' not null' else '' end,
          ''
        ), ', ' order by a.attnum)
     from pg_attribute a
     left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
     where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped),
    coalesce((select ', primary key (' || string_agg(quote_ident(a.attname), ', ' order by a.attnum) || ')'
              from pg_index i
              join pg_attribute a on a.attrelid = i.indrelid and a.attnum = any (i.indkey)
              where i.indrelid = c.oid and i.indisprimary), '')
  ), E'\n' order by c.relname) || E'\n\nnotify pgrst, ''reload schema'';' as ddl_to_run_in_new_project
from pg_class c
join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public'
  and c.relkind in ('r', 'p')
  and c.relname in (
    'agent_job_embed_state', 'agent_job_pieces', 'ats_import_audit', 'company_ats_config', 'customers',
    'graduate_roles', 'ireland_sponsored_companies', 'reported_jobs', 'subscriptions', 'sync_run_summary',
    'user_applied_jobs', 'user_favorite_companies', 'user_preferences'
  );
