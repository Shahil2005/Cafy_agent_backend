/**
 * Generates scripts/dev/testing_jobs_setup.sql from the live structure export
 * (scripts/dev/live_jobs_schema.csv, made by exportJobsSchema.sql run read-only on LIVE).
 *
 *   npx ts-node --transpile-only scripts/dev/buildTestingSetup.ts
 *
 * The generated SQL is for the TESTING Supabase project only. It:
 * - stops at once unless it is running in testing (live has `mentors`, testing has `user_applied_jobs`)
 * - renames testing's existing jobs-side tables to <name>_backup_20261102 (nothing is deleted)
 * - creates fresh tables, constraints, indexes, search functions and the search trigger exactly as on live
 * - runs as one transaction: all or nothing
 *
 * This script only reads the CSV and writes the .sql file. It connects to no database.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const DIR = path.join(__dirname);
const BACKUP = '_backup_20261102';
const INDEX_SUFFIX = '_bk20261102';
/** Creation and copy order (companies first: the part-time tables reference it). */
export const TABLES = ['companies', 'part_time_companies_UK', 'part_time_jobs_UK', 'jobs', 'jobs_IR', 'directory_employers', 'job_reports'];
/** Resume-side functions (SOC search) are not part of the jobs copy. */
const SKIP_FUNCTIONS = /^match_soc_occupations/;
/** Highest live ids on 2026-11-02, plus headroom, so ids made in testing never clash with copied ones. */
const SEQUENCE_START: Record<string, number> = { jobs_id_seq: 3_731_987, jobs_IR_id_seq: 634_666, part_time_jobs_UK_id_seq: 970_347 };

interface Row {
    kind: string;
    name: string;
    detail: Record<string, unknown>;
}

export function parseCsv(text: string): string[][] {
    const rows: string[][] = [];
    let row: string[] = [];
    let field = '';
    let quoted = false;
    for (let i = 0; i < text.length; i++) {
        const c = text[i]!;
        if (quoted) {
            if (c === '"' && text[i + 1] === '"') {
                field += '"';
                i++;
            } else if (c === '"') quoted = false;
            else field += c;
        } else if (c === '"') quoted = true;
        else if (c === ',') {
            row.push(field);
            field = '';
        } else if (c === '\n') {
            row.push(field.replace(/\r$/, ''));
            rows.push(row);
            row = [];
            field = '';
        } else field += c;
    }
    if (field || row.length) rows.push([...row, field]);
    return rows;
}

const ident = (name: string) => `"${name.replace(/"/g, '""')}"`;
const literal = (value: string) => `'${value.replace(/'/g, "''")}'`;
/** Runs one statement only if `condition` (SQL) is true. */
const when = (condition: string, statement: string) => `DO $cafy$ BEGIN IF ${condition} THEN EXECUTE ${literal(statement)}; END IF; END $cafy$;`;

export function buildSetupSql(rows: Row[]): string {
    const of = (kind: string) => rows.filter((r) => r.kind === kind);
    const tables = new Set(TABLES);
    const out: string[] = [];
    const add = (...lines: string[]) => out.push(...lines, '');

    add(
        '-- CAFY: make the TESTING jobs tables an exact copy of live\'s structure.',
        '-- Generated by scripts/dev/buildTestingSetup.ts from the read-only live export. Run in TESTING only.',
        '-- Nothing is deleted: existing testing tables are renamed to <name>' + BACKUP + '.',
        'BEGIN;',
        'SET LOCAL check_function_bodies = off;',
    );

    add(
        '-- 1. Safety: stop unless this is the testing database.',
        `DO $cafy$ BEGIN
  IF to_regclass('public.mentors') IS NOT NULL THEN
    RAISE EXCEPTION 'STOP: this is not the testing database. Nothing was changed.';
  END IF;
END $cafy$;`,
    );

    add(
        '-- 2. Keep the old testing tables as backups (renamed with their indexes and sequences). Skipped on a re-run.',
        `DO $cafy$
DECLARE t text; r record;
BEGIN
  IF to_regclass('public.cafy_testing_replica') IS NOT NULL THEN
    RAISE NOTICE 'Already set up before: backups kept as they are';
    RETURN;
  END IF;
  FOREACH t IN ARRAY ARRAY[${TABLES.map(literal).join(', ')}] LOOP
    IF to_regclass(format('public.%I', t)) IS NULL THEN CONTINUE; END IF;
    FOR r IN SELECT i.relname FROM pg_index x JOIN pg_class i ON i.oid = x.indexrelid WHERE x.indrelid = format('public.%I', t)::regclass LOOP
      EXECUTE format('ALTER INDEX public.%I RENAME TO %I', r.relname, left(r.relname, 50) || '${INDEX_SUFFIX}');
    END LOOP;
    FOR r IN SELECT s.relname FROM pg_class s JOIN pg_depend d ON d.objid = s.oid
             WHERE s.relkind = 'S' AND d.refobjid = format('public.%I', t)::regclass AND d.deptype IN ('a', 'i') LOOP
      EXECUTE format('ALTER SEQUENCE public.%I RENAME TO %I', r.relname, left(r.relname, 50) || '${INDEX_SUFFIX}');
    END LOOP;
    EXECUTE format('ALTER TABLE public.%I RENAME TO %I', t, t || '${BACKUP}');
  END LOOP;
END $cafy$;`,
    );

    const extensions = of('extension').filter((e) => ['pg_trgm', 'vector'].includes(e.name));
    add('-- 3. Extensions used by search.', ...extensions.map((e) => `CREATE EXTENSION IF NOT EXISTS ${ident(e.name)} WITH SCHEMA ${ident(String(e.detail.schema))};`));

    const sequences = of('sequence').filter((s) => tables.has(String(s.detail.owner ?? '')));
    add('-- 4. Id sequences.', ...sequences.map((s) => `CREATE SEQUENCE IF NOT EXISTS public.${ident(s.name)};`));

    add('-- 5. Tables, exactly as on live.');
    for (const table of TABLES) {
        const columns = of('column')
            .filter((c) => c.detail.table === table)
            .sort((a, b) => Number(a.detail.position) - Number(b.detail.position))
            .map((c) => {
                const d = c.detail;
                const parts = [ident(String(d.column)), String(d.type)];
                if (d.generated) parts.push(`GENERATED ALWAYS AS (${d.generated}) STORED`);
                else if (d.default) parts.push(`DEFAULT ${d.default}`);
                if (d.notNull) parts.push('NOT NULL');
                return `  ${parts.join(' ')}`;
            });
        if (!columns.length) throw new Error(`No columns for ${table} in the export`);
        add(`CREATE TABLE IF NOT EXISTS public.${ident(table)} (\n${columns.join(',\n')}\n);`);
    }
    for (const s of sequences) {
        const column = of('column').find((c) => c.detail.table === s.detail.owner && String(c.detail.default ?? '').includes(s.name));
        if (column) add(`ALTER SEQUENCE public.${ident(s.name)} OWNED BY public.${ident(String(s.detail.owner))}.${ident(String(column.detail.column))};`);
        if (SEQUENCE_START[s.name]) add(`SELECT setval('public.${ident(s.name)}', ${SEQUENCE_START[s.name]});`);
    }

    // Primary and unique keys first, then checks, then foreign keys (which need the keys).
    const constraintOrder = ['p', 'u', 'c', 'f'];
    const constraints = of('constraint')
        .filter((c) => tables.has(String(c.detail.table)))
        .sort((a, b) => constraintOrder.indexOf(String(a.detail.type)) - constraintOrder.indexOf(String(b.detail.type)));
    add(
        '-- 6. Keys and rules.',
        ...constraints.map((c) =>
            when(
                `NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = ${literal(c.name)} AND conrelid = ${literal(`public.${ident(String(c.detail.table))}`)}::regclass)`,
                `ALTER TABLE public.${ident(String(c.detail.table))} ADD CONSTRAINT ${ident(c.name)} ${c.detail.def}`,
            ),
        ),
    );

    const constraintNames = new Set(constraints.map((c) => c.name));
    const indexes = of('index').filter((i) => tables.has(String(i.detail.table)) && !constraintNames.has(i.name));
    add('-- 7. Search indexes.', ...indexes.map((i) => `${String(i.detail.def).replace(/^CREATE (UNIQUE )?INDEX /, (m) => `${m}IF NOT EXISTS `)};`));

    const functions = of('function').filter((f) => !SKIP_FUNCTIONS.test(f.name));
    add('-- 8. Search functions.', ...functions.map((f) => `${String(f.detail.def).trim()};`));

    add('-- 9. Search trigger.', ...of('trigger').filter((t) => tables.has(String(t.detail.table))).map((t) => `${String(t.detail.def).replace(/^CREATE TRIGGER /, 'CREATE OR REPLACE TRIGGER ')};`));

    const rls = of('table').filter((t) => tables.has(t.name) && t.detail.rls);
    add('-- 10. Row level security, as on live.', ...rls.map((t) => `ALTER TABLE public.${ident(t.name)} ENABLE ROW LEVEL SECURITY;`));

    add(
        '-- 11. Marker: tells a re-run and the copy script that this setup was applied.',
        'CREATE TABLE IF NOT EXISTS public.cafy_testing_replica (built_at timestamptz NOT NULL DEFAULT now(), note text);',
        'ALTER TABLE public.cafy_testing_replica ENABLE ROW LEVEL SECURITY;',
        "INSERT INTO public.cafy_testing_replica (note) VALUES ('jobs side copied from live structure export');",
        'COMMIT;',
    );
    return out.join('\n');
}

function main(): void {
    const csv = parseCsv(readFileSync(path.join(DIR, 'live_jobs_schema.csv'), 'utf8'));
    const [header, ...body] = csv;
    if (header?.join(',') !== 'kind,name,detail') throw new Error('Unexpected export file: expected columns kind,name,detail');
    const rows: Row[] = body.filter((r) => r.length === 3).map(([kind, name, detail]) => ({ kind: kind!, name: name!, detail: JSON.parse(detail!) }));
    const sql = buildSetupSql(rows);
    // Real removal commands only ("ON DELETE CASCADE" in a key rule is not one).
    const removal = /\b(?:DROP\s+(?:TABLE|SCHEMA|INDEX|FUNCTION|TRIGGER|SEQUENCE|POLICY|COLUMN|CONSTRAINT|EXTENSION)|TRUNCATE|DELETE\s+FROM)\b/i.exec(sql);
    if (removal) throw new Error(`Refusing to write: generated SQL contains "${removal[0]}"`);
    writeFileSync(path.join(DIR, 'testing_jobs_setup.sql'), sql);
    console.log(`Wrote scripts/dev/testing_jobs_setup.sql (${sql.length.toLocaleString()} characters)`);
}

if (require.main === module) main();
